static uint64_t book_prng_state = 0x853c49e6748fea9bULL;

static inline uint32_t book_rand(void) {
    book_prng_state ^= book_prng_state >> 12;
    book_prng_state ^= book_prng_state << 25;
    book_prng_state ^= book_prng_state >> 27;
    return (uint32_t)((book_prng_state * 0x2545F4914F6CDD1DULL) >> 32);
}

static int cmp_book_key(const void *a, const void *b) {
    uint64_t ka = *(const uint64_t *)a;
    uint64_t kb = *(const uint64_t *)b;
    if (ka < kb) return -1;
    if (ka > kb) return 1;
    return 0;
}

void init_book(void) {
    book_prng_state ^= get_time_ms();
}

move_t probe_book(const struct Board *b) {
    if (!option_own_book || BOOK_SIZE == 0) return 0;
    uint64_t key = board_key(b);
    const uint64_t *match = (const uint64_t *)bsearch(
        &key, book_keys, BOOK_SIZE, sizeof(uint64_t), cmp_book_key);
    if (!match) return 0;

    int first = (int)(match - book_keys);
    while (first > 0 && book_keys[first - 1] == key)
        first--;

    int last = first;
    int total_weight = 0;
    while (last < BOOK_SIZE && book_keys[last] == key) {
        total_weight += book_weights[last];
        last++;
    }

    if (total_weight <= 0) return book_moves[first];

    int r = (int)(book_rand() % (uint32_t)total_weight);
    int acc = 0;
    for (int i = first; i < last; ++i) {
        acc += book_weights[i];
        if (r < acc) return book_moves[i];
    }
    return book_moves[first];
}
